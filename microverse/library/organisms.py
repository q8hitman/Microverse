@dataclass(frozen=True)
class Organism:
    # --- identity
    key: str
    name: str
    name_ar: str
    common: str
    common_ar: str
    group: str
    group_ar: str
    ncbi_taxid: int
    lineage: tuple[str, ...]
    # --- appearance
    size_um: float                     # typical longest dimension
    size_text: str
    shape: str
    shape_ar: str
    draw: str                          # how the renderer draws it: coccus/chain/rod/sphere/filament/ciliate/amoeba/flagellate/yeast/hypha/rotifer/diatom
    colour: str
    gram: str                          # "+", "-", "na"
    motility: str
    motility_ar: str
    # --- physiology used by the simulation
    feeding: str
    oxygen: str
    substrates: tuple[str, ...]        # organic/inorganic pools it can consume
    products: dict[str, float]         # mg product per mg substrate consumed (fermentation)
    hydrolysis: float                  # mg polymer broken to sugar per mg biomass per h
    mu_max: float                      # 1/h at optimum
    ks: float                          # mg/L half-saturation for its substrate
    yield_bio: float                   # mg biomass per mg substrate
    cardinal_T: tuple[float, float, float]      # Tmin, Topt, Tmax (°C)
    cardinal_pH: tuple[float, float, float]     # pHmin, pHopt, pHmax
    death: float                       # 1/h basal death rate
    edible: bool                       # can be eaten by predators
    prey_size_max: float = 0.0         # predators only: largest prey it can ingest (µm)
    ingest_max: float = 0.0            # predators only: mg prey per mg predator per h
    ks_prey: float = 0.0               # predators only: mg/L
    n_quota: float = 0.1               # mg N per mg biomass
    # --- description
    metabolism: str = ""
    metabolism_ar: str = ""
    habitat: str = ""
    habitat_ar: str = ""
    reproduction: str = ""
    reproduction_ar: str = ""
    role: str = ""
    role_ar: str = ""
    applications: str = ""
    applications_ar: str = ""
    biosafety: str = "Biosafety level 1 (harmless); used in teaching labs."
    biosafety_ar: str = "مستوى السلامة الحيوية 1 (غير ممرض)، يُستخدم في مختبرات التدريس."
    trait_evidence: Evidence = Evidence.LITERATURE_ESTIMATE
    model_variables: tuple[str, ...] = ()
    notes: tuple[str, ...] = ()
    references: tuple[str, ...] = field(default_factory=tuple)

    @property
    def feeding_label(self) -> tuple[str, str]:
        return FEEDING_LABELS[self.feeding]

    @property
    def oxygen_label(self) -> tuple[str, str]:
        return OXYGEN_LABELS[self.oxygen]


def _o(**kw) -> Organism:
    return Organism(**kw)


